from typing import Optional, Dict, Any
from beanie import PydanticObjectId, Indexed
from pydantic import Field

from app.models.base import WorkspaceScopedDocument
from app.enums import DeliverableStatus, DeliverableType


class Deliverable(WorkspaceScopedDocument):
    """
    Structured Deliverable generated by an AI Agent inside the chat.
    """
    hired_agent_id: PydanticObjectId = Field(..., index=True, description="Agent who generated this deliverable")
    conversation_id: PydanticObjectId = Field(..., index=True, description="Parent chat conversation ID")
    
    # Identifier shown on card (e.g. STRAT-6, DOC-12)
    tracking_code: str = Field(..., description="Short tracking code (e.g. 'STRAT-6')")
    title: str = Field(..., description="Deliverable title (e.g. '30-Day Growth Sprint Plan')")
    deliverable_type: DeliverableType = Field(default=DeliverableType.MARKETING_PLAN)
    
    # Content
    summary: str = Field(..., description="High-level objective / preview")
    content_markdown: str = Field(..., description="Full text / Markdown deliverable body")
    structured_data: Dict[str, Any] = Field(default_factory=dict, description="JSON payload / tabular metrics")
    
    # Review & Feedback
    status: DeliverableStatus = Field(
        default=DeliverableStatus.DRAFT,
        index=True,
        description="Approval / review state"
    )
    user_feedback: Optional[str] = Field(default=None, description="User's feedback note")
    
    # Integration sync status (e.g., Notion, Google Drive)
    synced_integration: Optional[str] = Field(
        default=None,
        description="Name of synced integration (e.g. 'Notion', 'Google Drive')"
    )
    synced_external_url: Optional[str] = Field(
        default=None,
        description="Direct URL to the created document inside the connected tool"
    )

    class Settings:
        name = "deliverables"


# Alias for backward compatibility
Artifact = Deliverable
ArtifactType = DeliverableType
